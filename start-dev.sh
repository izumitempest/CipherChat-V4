#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# CipherChat dev launcher — starts the WHOLE system:
#
#   web  (Next.js dev)         http://localhost:3000
#   relay (socket.io)          http://localhost:3003
#   presence/terminate (int.)  http://127.0.0.1:3004  (token-guarded)
#
# What it does, in order:
#   1. Fills in any MISSING vars in .env (never overwrites existing values):
#        RELAY_INTERNAL_TOKEN   random 48-hex (openssl, /dev/urandom fallback)
#        DATABASE_URL           <repo>/db/custom.db (absolute, created)
#        NEXT_PUBLIC_RELAY_URL  http://localhost:3003   (or LAN IP with --lan)
#        NEXT_PUBLIC_SITE_URL   http://localhost:3000
#   2. Generates the Prisma client (once) and pushes the schema (idempotent).
#   3. Stops anything already on ports 3000/3003/3004 (stale instances).
#   4. Starts relay + web DETACHED (setsid: they survive this shell, the
#      terminal closing, and process-group kills), logs to dev.log /
#      relay-dev.log, pids in .run/.
#   5. Waits until all three ports answer, then prints where to go.
#
# Usage:
#   ./start-dev.sh            start everything (stop stale first)
#   ./start-dev.sh --lan      same, plus two quick tunnels (app and relay) so
#                             a phone can open the room over https; plain
#                             http on a LAN address is not a secure context,
#                             and WebCrypto needs one
#   ./start-dev.sh status     are the services up?
#   ./start-dev.sh stop       stop everything the script knows about
#   ./start-dev.sh restart    stop + start
#
# Requires: bun, curl, ss (iproute2). openssl optional (token generation).
# ---------------------------------------------------------------------------
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$ROOT"

WEB_PORT=3000
RELAY_PORT=3003
PRESENCE_PORT=3004
RUN_DIR="$ROOT/.run"
LOG_WEB="$ROOT/dev.log"
LOG_RELAY="$ROOT/relay-dev.log"

# --- helpers ---------------------------------------------------------------

say()  { printf '\033[1;32m[dev]\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[dev]\033[0m %s\n' "$*" >&2; }
die()  { printf '\033[1;31m[dev]\033[0m %s\n' "$*" >&2; exit 1; }

need() { command -v "$1" >/dev/null 2>&1 || die "missing dependency: $1 ($2)"; }
need bun "the relay service runs on bun (https://bun.sh)"
need curl "readiness checks"
need ss   "port checks (iproute2)"

rand_hex() { # 24 random bytes as hex
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex 24
  else
    head -c 24 /dev/urandom | od -An -tx1 | tr -d ' \n'
  fi
}

env_has() { grep -Eq "^$1=" .env 2>/dev/null; }

env_get() {
  grep -E "^$1=" .env 2>/dev/null | head -1 | cut -d= -f2- | sed -e 's/^"//' -e 's/"$//'
}

lan_ip() {
  # first non-loopback IPv4 the host advertises (strip any /CIDR suffix)
  (hostname -I 2>/dev/null || ip -4 -o addr 2>/dev/null | awk '{print $4}') \
    | tr ' ' '\n' | grep -Ev '^(127\.|::1)' | cut -d/ -f1 | grep -v '^$' | head -1 || true
}

port_pids() { # pids listening on $1
  ss -tlnp 2>/dev/null | grep -E "[:.]$1\b" | grep -oP 'pid=\K[0-9]+' | sort -u || true
}

stop_all() {
  say "stopping stale instances (if any)…"
  local killed=0
  # Host dev-server pattern only: the production compose stack runs
  # `next start`-style processes whose cmdlines do NOT match, and its
  # containerized relay shares this repo's path in its cmdline — a
  # broad "relay-service" pattern here would kill the share stack's
  # containers too. The dev relay is stopped by its HOST ports below
  # (container ports are namespaced away from the host).
  if pkill -f "next dev -p $WEB_PORT" 2>/dev/null; then killed=1; fi
  # The quick tunnels from --lan mode.
  if [ -f "$RUN_DIR/tunnel-relay.pid" ]; then
    kill "$(cat "$RUN_DIR/tunnel-relay.pid")" 2>/dev/null || true
    killed=1
  fi
  if [ -f "$RUN_DIR/tunnel-app.pid" ]; then
    kill "$(cat "$RUN_DIR/tunnel-app.pid")" 2>/dev/null || true
    killed=1
  fi
  for port in $WEB_PORT $RELAY_PORT $PRESENCE_PORT; do
    local pids; pids="$(port_pids "$port")"
    if [ -n "$pids" ]; then
      kill $pids 2>/dev/null || true
      killed=1
    fi
  done
  if [ -n "$(port_pids "$WEB_PORT")$(port_pids "$RELAY_PORT")$(port_pids "$PRESENCE_PORT")" ]; then
    sleep 1
    for port in $WEB_PORT $RELAY_PORT $PRESENCE_PORT; do
      local pids2; pids2="$(port_pids "$port")"
      [ -n "$pids2" ] && kill -9 $pids2 2>/dev/null || true
    done
  fi
  rm -f "$RUN_DIR"/*.pid 2>/dev/null || true
  [ "$killed" = 1 ] && say "stopped." || say "nothing was running."
}

# --- 1. environment ---------------------------------------------------------

ensure_env() {
  if [ ! -f .env ]; then
    say "no .env found — creating one"
    printf '# CipherChat dev environment (generated by start-dev.sh)\n' > .env
  fi

  if ! env_has RELAY_INTERNAL_TOKEN || [ -z "$(env_get RELAY_INTERNAL_TOKEN)" ]; then
    local tok; tok="$(rand_hex)"
    {
      printf '\n# Shared secret web<->relay (auto-generated %s)\n' "$(date +%F)"
      printf 'RELAY_INTERNAL_TOKEN=%s\n' "$tok"
    } >> .env
    say "generated RELAY_INTERNAL_TOKEN"
  else
    say "RELAY_INTERNAL_TOKEN present (kept)"
  fi

  if ! env_has DATABASE_URL; then
    mkdir -p "$ROOT/db"
    {
      printf '\n# SQLite database (auto)\n'
      printf 'DATABASE_URL="file:%s/db/custom.db"\n' "$ROOT"
    } >> .env
    say "set DATABASE_URL to $ROOT/db/custom.db"
  else
    say "DATABASE_URL present (kept: $(env_get DATABASE_URL))"
  fi

  # The browser-facing relay URL. With --lan the relay is reached through
  # its own quick tunnel (https), because a page on https cannot open a
  # ws:// socket, and a LAN address over plain http is not a secure
  # context at all.
  local desired_relay="http://localhost:$RELAY_PORT"
  if [ "${LAN_MODE:-0}" = 1 ]; then
    desired_relay="__TUNNEL__"
  fi
  if [ "$desired_relay" = "__TUNNEL__" ]; then
    say "NEXT_PUBLIC_RELAY_URL will be the relay's tunnel URL (--lan)"
  elif ! env_has NEXT_PUBLIC_RELAY_URL; then
    printf '\n# Where the browser finds the relay (auto)\n' >> .env
    printf 'NEXT_PUBLIC_RELAY_URL=%s\n' "$desired_relay" >> .env
    say "set NEXT_PUBLIC_RELAY_URL=$desired_relay"
  else
    say "NEXT_PUBLIC_RELAY_URL present (kept: $(env_get NEXT_PUBLIC_RELAY_URL))"
  fi

  if ! env_has NEXT_PUBLIC_SITE_URL; then
    printf '\nNEXT_PUBLIC_SITE_URL=http://localhost:%s\n' "$WEB_PORT" >> .env
    say "set NEXT_PUBLIC_SITE_URL"
  fi
}

# --- 2. database ------------------------------------------------------------

ensure_db() {
  mkdir -p "$ROOT/db"
  if [ ! -d node_modules/.prisma/client ]; then
    say "generating Prisma client…"
    bunx prisma generate
  fi
  say "applying migrations to the dev database…"
  # The same step the production container runs: back up, baseline if
  # the database predates the migrations, apply what is pending.
  bun "$ROOT/deploy/entrypoint-migrate.mjs"
}

# --- 4. launch --------------------------------------------------------------

start_all() {
  mkdir -p "$RUN_DIR"
  # shellcheck disable=SC1091
  set -a; source .env; set +a
  : "${RELAY_INTERNAL_TOKEN:?RELAY_INTERNAL_TOKEN missing in .env}"

  say "starting relay (:$RELAY_PORT, presence :$PRESENCE_PORT)…"
  setsid bun "$ROOT/mini-services/relay-service/index.ts" \
    >> "$LOG_RELAY" 2>&1 < /dev/null &
  echo $! > "$RUN_DIR/relay.pid"

  say "starting web (Next.js dev :$WEB_PORT)…"
  setsid npx next dev -p "$WEB_PORT" \
    >> "$LOG_WEB" 2>&1 < /dev/null &
  echo $! > "$RUN_DIR/web.pid"

  # --- 5. readiness ---------------------------------------------------------
  say "waiting for services"
  local deadline=$((SECONDS + 90)) web_ok=0 relay_ok=0 presence_ok=0
  while [ $SECONDS -lt $deadline ]; do
    [ "$web_ok" = 0 ] && curl -sf -o /dev/null "http://127.0.0.1:$WEB_PORT/" && web_ok=1
    [ "$relay_ok" = 0 ] && curl -sf -o /dev/null "http://127.0.0.1:$RELAY_PORT/?EIO=4&transport=polling" && relay_ok=1
    [ "$presence_ok" = 0 ] && curl -sf -o /dev/null -H "x-internal-token: $RELAY_INTERNAL_TOKEN" \
      "http://127.0.0.1:$PRESENCE_PORT/presence/status" && presence_ok=1
    if [ "$web_ok$relay_ok$presence_ok" = "111" ]; then break; fi
    sleep 1
  done

  echo
  if [ "$web_ok$relay_ok$presence_ok" != "111" ]; then
    warn "not everything came up (web:$web_ok relay:$relay_ok presence:$presence_ok)"
    warn "logs: $LOG_WEB / $LOG_RELAY"
    exit 1
  fi

  local lan; lan="$(lan_ip)"
  printf '\033[1m  CipherChat is up\033[0m\n'
  printf '    local:   http://localhost:%s\n' "$WEB_PORT"
  if [ -n "$app_url" ]; then
    printf '    phone:   %s   (https, the tunnel; a LAN http address will not do)\n' "$app_url"
    printf '    relay:   %s\n' "$relay_tunnel_url"
  elif [ -n "$lan" ]; then
    printf '    LAN:     http://%s:%s   (plain http: the crypto will not run there)\n' "$lan" "$WEB_PORT"
  fi
  printf '    logs:    %s, %s\n' "$LOG_WEB" "$LOG_RELAY"
  printf '    stop:    ./start-dev.sh stop\n'
  printf '    status:  ./start-dev.sh status\n'
}

status_all() {
  # shellcheck disable=SC1091
  [ -f .env ] && { set -a; source .env; set +a; }
  local ok=1
  for spec in "web:$WEB_PORT" "relay:$RELAY_PORT" "presence:$PRESENCE_PORT"; do
    local name="${spec%%:*}" port="${spec##*:}" pids
    pids="$(port_pids "$port")"
    if [ -n "$pids" ]; then
      printf '  %-8s :%s  up (pid %s)\n' "$name" "$port" "$(echo $pids | tr '\n' ' ')"
    else
      printf '  %-8s :%s  DOWN\n' "$name" "$port"
      ok=0
    fi
  done
  if [ "$ok" = 1 ]; then
    curl -sf -o /dev/null -H "x-internal-token: ${RELAY_INTERNAL_TOKEN:-}" \
      "http://127.0.0.1:$PRESENCE_PORT/presence/status" \
      && echo '  internal token: armed and answering' \
      || { echo '  internal token: NOT answering (check RELAY_INTERNAL_TOKEN)'; ok=0; }
  fi
  [ "$ok" = 1 ] || exit 1
}

# --- entry ------------------------------------------------------------------

CMD="${1:-up}"
case "$CMD" in
  up)
    [ "${2:-}" = "--lan" ] || [ "${1:-}" = "--lan" ] && LAN_MODE=1
    ;;
esac
# allow `./start-dev.sh --lan` (no subcommand)
if [ "$CMD" = "--lan" ]; then CMD="up"; LAN_MODE=1; fi

case "$CMD" in
  up)       ensure_env; ensure_db; stop_all; start_all ;;
  stop)     stop_all ;;
  status)   status_all ;;
  restart)  ensure_env; ensure_db; stop_all; start_all ;;
  *) die "unknown command: $CMD (use: up [--lan] | stop | status | restart)" ;;
esac
